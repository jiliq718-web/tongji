-- Chạy toàn bộ file này trong Supabase > SQL Editor > New query.
-- Bảng thống kê độc lập, không dùng bảng chấm công.
create table if not exists public.agent_stats (
  id bigint generated by default as identity primary key,
  agent_id text not null,
  report_date date not null,
  daily_salary numeric,
  ad_funds numeric,
  commission numeric,
  video_promotion numeric,
  total_expense numeric,
  level1_deposit numeric,
  level1_withdrawal numeric,
  level2_deposit numeric,
  total_assets numeric,
  total_withdrawals numeric,
  internal_profit numeric,
  external_profit numeric,
  storage_diff numeric,
  total_profit numeric,
  profit_percent numeric,
  handling_fee numeric,
  new_ad_status text,
  cooperation_status text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint agent_stats_agent_date_unique unique (agent_id, report_date)
);

alter table public.agent_stats enable row level security;

-- Chỉ người dùng đã đăng nhập mới được xem/sửa dữ liệu.
drop policy if exists "Signed-in users can read agent stats" on public.agent_stats;
create policy "Signed-in users can read agent stats"
  on public.agent_stats for select to authenticated using (true);

drop policy if exists "Signed-in users can insert agent stats" on public.agent_stats;
create policy "Signed-in users can insert agent stats"
  on public.agent_stats for insert to authenticated with check (true);

drop policy if exists "Signed-in users can update agent stats" on public.agent_stats;
create policy "Signed-in users can update agent stats"
  on public.agent_stats for update to authenticated using (true) with check (true);

-- Cho phép người đã đăng nhập xóa dòng dữ liệu nếu sau này cần.
drop policy if exists "Signed-in users can delete agent stats" on public.agent_stats;
create policy "Signed-in users can delete agent stats"
  on public.agent_stats for delete to authenticated using (true);

create index if not exists agent_stats_date_idx on public.agent_stats(report_date);
create index if not exists agent_stats_agent_idx on public.agent_stats(agent_id);
